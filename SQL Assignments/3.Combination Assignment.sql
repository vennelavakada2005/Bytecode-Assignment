-- HAVING -- LOGICAL OPERATORS,AGGREGATE FUNCTION --
USE NINEAM_CLASS;
SELECT * FROM RETAIL_ORDERS;

-- FETCH CATEGORY WISE TOTAL SALES
SELECT CATEGORY,SUM(SALES) AS TOTAL_SALES
FROM RETAIL_ORDERS
GROUP BY CATEGOTY
HAVING SUM(SALES)>100000;

SELECT CITY,SUM(SALES) AS TOTAL_SALES
FROM RETAIL_ORDERS
GROUP BY CITY
HAVING SUM(SALES)>100000;

SELECT COUNT(SALES) AS COUNT_SALES
FROM RETAIL_ORDERS
GROUP BY CITY
HAVING COUNT(SALES)>3;

SELECT CUSTOMER_ID, COUNT(SALES) AS COUNT_SALES
FROM RETAIL_ORDERS
GROUP BY CUSTOMER_ID
HAVING COUNT(SALES)>1;

/*-- FIND CUSTOMER WHO PLACED MORE THAN 1 ORDER SPENT MORE THAN 2000 IN TOTAL
SHOW THEIR TOTAL ORDERS AND TOTAL SALES
MORE THAN 1 ORDER AND
SPENT MORE THAN 2000
CUSTOMER
COUNT(ORDERS),SUM(SALES)
*/
SELECT CUSTOMER_ID,SUM(SALES) AS TOTAL_SALES,COUNT(ORDER_ID) TOTAL_ORDERS
FROM RETAIL_ORDERS
GROUP BY CUSTOMER_ID
HAVING SUM(SALES)>2000 AND COUNT(ORDER_ID)>1;

SELECT SUB_CATEGORY,SUM(QUANTITY) AS TOTAL_QUANTITY,SUM(PROFIT) AS TOTAL_PROFIT
FROM RETAIL_ORDERS
GROUP BY SUB_CATEGORY
HAVING SUM(QUANTITY) AND SUM(PROFIT);

-- WHERE GROUP BY,HAVING
SELECT CATEGORY,CITY,SUM(SALES) TOTAL_SALES
FROM RETAIL_ORDERS
WHERE CITY="HYDERABAD"
GROUP BY CITY,CATEGORY
HAVING TOTAL_SALES>50000;

SELECT PROFIT,CITY,SUM(PROFIT) TOTAL_PROFIT
FROM RETAIL_ORDERS
WHERE CITY="TECHNOLOGY"
GROUP BY CITY,PROFIT
HAVING TOTAL_PROFIT>5000;

SELECT ORDER_DATE,CATEGORY,SUM(SALES) TOTAL_SALES
FROM RETAIL_ORDERS
WHERE ORDER_DATE>2023-02-01
GROUP BY CATEGORY,CITY,ORDER_DATE
HAVING TOTAL_SALES>40000;

SELECT CITY,ORDER_DATE,SUM(PROFIT) TOTAL_PROFIT
FROM RETAIL_ORDERS 
WHERE ORDER_DATE  BETWEEN '2023-03-01' AND '2023-04-30'
GROUP BY ORDER_DATE,CITY
HAVING TOTAL_PROFIT>4000;

SELECT CUSTOMER_ID,SUM(SALES) TOTAL_SALES
FROM RETAIL_ORDERS
GROUP BY CUSTOMER_ID
ORDER BY SUM(SALES) DESC
LIMIT 5;




