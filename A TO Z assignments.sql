 SELECT ORDER_DATE,DATE_FORMAT(ORDER_DATE,"%a") AS SHORT_DAYNAME,
  DATE_FORMAT(ORDER_DATE,"%b") AS MONTH_SHORT_DAYNAME,
  DATE_FORMAT(ORDER_DATE,"%c") AS MONTH_SHORT_DAYNAME,
   DATE_FORMAT(ORDER_DATE,"%D") AS SHORT_SUFFIX_MONTHNAME,
    DATE_FORMAT(ORDER_DATE,"%d") AS SHORT_SUFFIX_MONTHNAME,
 DATE_FORMAT(ORDER_DATE,"%e") AS SHORT_NUMERIC_MONTHNAME,
 DATE_FORMAT(ORDER_DATE,"%f") AS MICRO_SECONDS,
 DATE_FORMAT(ORDER_DATE,"%H") AS HOUR,
  DATE_FORMAT(ORDER_DATE,"%h") AS HOUR,
  DATE_FORMAT(ORDER_DATE,"%I") AS HOUR,
  DATE_FORMAT(ORDER_DATE,"%i") AS MINUTES,
   DATE_FORMAT(ORDER_DATE,"%j") AS DAYOF_THEYEAR,
   DATE_FORMAT(ORDER_DATE,"%k") AS HOUR,
    DATE_FORMAT(ORDER_DATE,"%l") AS HOUR,
    DATE_FORMAT(ORDER_DATE,"%M") AS MONTHNAME_INFULL,
     DATE_FORMAT(ORDER_DATE,"%m") AS NUMERIC_VALUE,
     DATE_FORMAT(ORDER_DATE,"%p") AS AM_PM,
     DATE_FORMAT(ORDER_DATE,"%r") AS TIME_FORMAT,
      DATE_FORMAT(ORDER_DATE,"%S") AS SECONDS,
      DATE_FORMAT(ORDER_DATE,"%s") AS SECONDS,
      DATE_FORMAT(ORDER_DATE,"%T") AS HOUR_FORMAT,
      DATE_FORMAT(ORDER_DATE,"%U") AS SUNDAY_WEEK,
      DATE_FORMAT(ORDER_DATE,"%u") AS MONDAY_ISFIRST,
       DATE_FORMAT(ORDER_DATE,"%V") AS FIRSTDAY_OFWEEK,
       DATE_FORMAT(ORDER_DATE,"%v") AS  MONDAYIS_FIRSTDAY,
        DATE_FORMAT(ORDER_DATE,"%W") AS  WEEKDAY_NAMEISFULL,
        DATE_FORMAT(ORDER_DATE,"%w") AS  DAYOF_WEEK,
        DATE_FORMAT(ORDER_DATE,"%X") AS  YEAROF_WEEK,
        DATE_FORMAT(ORDER_DATE,"%x") AS  YEAROF_WEEK,
         DATE_FORMAT(ORDER_DATE,"%Y") AS  YEARAS_ANUMERIC,
         DATE_FORMAT(ORDER_DATE,"%y") AS  YEARAS_ANUMERIC
        FROM DATE_DATA_ORDERS;
 